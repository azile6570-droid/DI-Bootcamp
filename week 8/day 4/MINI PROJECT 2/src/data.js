export const allPhotos = Object.entries(galleryByCategory).flatMap(([category, photos]) =>
  photos.map((photo) => ({ ...photo, category })),
);

export function getCategoryPhotos(category) {
  return galleryByCategory[category] ?? galleryByCategory.mountain;
}

export function getSearchPhotos(term) {
  const query = term.trim().toLowerCase();

  if (!query) {
    return allPhotos.slice(0, 12);
  }

  const matches = allPhotos.filter((photo) => {
    const categoryMatch = photo.category.toLowerCase().includes(query);
    const altMatch = photo.alt.toLowerCase().includes(query);
    return categoryMatch || altMatch;
  });

  return matches.length ? matches : allPhotos.slice(0, 12);
}
